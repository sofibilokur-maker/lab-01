"""tokenizer.py — потоковий токенізатор з Unicode-нормалізацією.

Правила токенізації (задокументовано):
1. Unicode NFKC-нормалізація перед розбиттям (уніфікує сумісні символи:
   наприклад, повноширинні цифри → звичайні, ligatures → окремі літери).
2. Текст приводиться до нижнього регістру (case-insensitive пошук).
3. Апострофи всередині слова (don't, it's, O'Brien) зберігаються
   як частина токена — не розбивають слово.
4. Дефіси всередині слова (mother-in-law, well-known) зберігаються
   як частина токена.
5. Апостроф/дефіс на межі слова (лапки навколо слова, дефіс у кінці рядка
   як перенос) — не входять у токен, відсікаються.
6. Числа (цілі, з крапкою: 3.14, з комою: 1,000) розпізнаються
   як окремі токени.
7. Будь-яка інша пунктуація та пробіли — розділювачі, у токени не входять.
"""

import re
import unicodedata
from typing import Iterator

# Токен: послідовність літер/цифр, з можливими внутрішніми апострофами/дефісами/крапками(для чисел)
_TOKEN_PATTERN = re.compile(
    r"\d+[.,]\d+|\d+|[^\W\d_]+(?:['\-][^\W\d_]+)*",
    re.UNICODE,
)

def tokenize(text: str) -> Iterator[str]:
    """
    Потоковий токенізатор: приймає текст, повертає генератор токенів.
    Нормалізує Unicode (NFKC) і приводить до нижнього регістру.
    """
    normalized = unicodedata.normalize("NFKC", text).lower()
    for match in _TOKEN_PATTERN.finditer(normalized):
        yield match.group(0)